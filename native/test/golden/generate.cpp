// Golden vector generator — implementation plan Phase 3.
//
// RUN ONCE. Its output, native/test/golden/vectors.bin, is FROZEN: it is the
// contract C-01/C-02 compare devices against (contract §2.2). After it is
// committed, a mismatch is an encoder regression — never a reason to run this
// again.
//
//   itantra-golden-generate <output.bin> [--format-version-bump]
//
// Refuses to overwrite an existing file. --format-version-bump exists only for
// a deliberate packet-format or coder version bump, recorded in the packet
// spec change log (contract §7.2). Adding vectors for later phases (real Tier
// 1 / Tier 2 tables) is also a deliberate, recorded act, and must keep every
// existing vector byte-identical.
//
// Every vector is generated by assemble() and checked by parse() before the
// file is written, so a broken encoder cannot freeze a payload it cannot read.
//
// Inputs are pre-encryption (packet §6.10.1). The byte-symbol vectors stand in
// for literals and byte fallback: the Tier 2 subword vocabulary and the Tier 1
// tables do not exist until Phases 7 and 8, so here the symbols are the UTF-8
// bytes themselves, coded under a 256-symbol table with a non-zero floor.

