int main(int argc, char** argv) {
    if (argc < 2 || argc > 3 || (argc == 3 && std::strcmp(argv[2], "--format-version-bump") != 0)) {
        std::fprintf(stderr, "usage: itantra-golden-generate <output.bin> [--format-version-bump]\n");
        return 2;
    }
    const char* path = argv[1];
    if (golden::file_exists(path) && argc != 3) {
        std::fprintf(stderr,
                     "REFUSED: %s exists. Golden vectors are frozen (contract §2.2, §7.2).\n"
                     "A mismatch is an encoder regression. Regenerate only for a deliberate format\n"
                     "version bump recorded in the packet spec change log (--format-version-bump).\n",
                     path);
        return 1;
    }

    Builder b;
    build(b);

    auto payload = std::make_unique<NativePayload>();
    auto parsed  = std::make_unique<ParsedPayload>();
    for (golden::GoldenVector& v : b.file.vectors) {
        const golden::ScheduledModel model(b.file.models, v);
        const AssemblyInput in = golden::input_of(v, model);
        const AsmResult r = assemble(in, *payload);
        if (r != AsmResult::Ok) {
            std::fprintf(stderr, "generator: assemble failed for %s (%u)\n", v.name.c_str(), static_cast<u32>(r));
            return 3;
        }
        v.payload.assign(payload->bytes, payload->bytes + payload->len);
        v.metadata_bits = payload->metadata_bits;

        const golden::FixedSelector selector(&model);
        const ParseStatus ps = parse(v.payload.data(), static_cast<u32>(v.payload.size()), selector, *parsed);
        bool same = ps == ParseStatus::Ok && parsed->metadata == v.metadata &&
                    parsed->metadata_bits == v.metadata_bits;
        for (std::size_t i = 0u; same && i < v.symbols.size(); ++i) same = parsed->symbols[i] == v.symbols[i];
        if (!same) {
            std::fprintf(stderr, "generator: %s does not parse back to its input\n", v.name.c_str());
            return 3;
        }
    }

    const std::vector<u8> bytes = golden::serialize(b.file);
    golden::GoldenFile check;
    std::string error;
    if (!golden::deserialize(bytes, check, error) || check.vectors.size() != b.file.vectors.size()) {
        std::fprintf(stderr, "generator: serialised file does not load back: %s\n", error.c_str());
        return 3;
    }
    if (!golden::write_file(path, bytes)) {
        std::fprintf(stderr, "generator: cannot write %s\n", path);
        return 2;
    }

    std::printf("golden vectors: file v%u, packet format v%u, coder v%u, %zu tables, %zu vectors, %zu bytes, crc32 0x%08X\n",
                b.file.file_version, b.file.packet_format_version, b.file.coder_version, b.file.models.size(),
                b.file.vectors.size(), bytes.size(),
                golden::crc32(bytes.data(), bytes.size() - 4u));
    std::printf("%-44s tier count meta  len  first bytes\n", "vector");
    for (const golden::GoldenVector& v : b.file.vectors) {
        std::printf("%-44s  %u  %5zu  %3u %5zu ", v.name.c_str(), static_cast<u32>(v.metadata.tier),
                    v.symbols.size(), v.metadata_bits, v.payload.size());
        for (std::size_t i = 0u; i < v.payload.size() && i < 8u; ++i) std::printf(" %02X", v.payload[i]);
        std::printf("\n");
    }
    return 0;
}
